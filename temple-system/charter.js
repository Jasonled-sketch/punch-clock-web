// 章程與管理辦法範本引擎
// 骨架依內政部「非財團法人制寺廟組織或管理章程範例」與寺廟登記須知應記載 12 事項：
// 名稱、宗教別及主祀神祇、所在地、宗旨、事業、信徒資格、組織及管理方式、
// 管理／監察人員名額職權任期產生方式、會議召開條件及決議方式、財務及會計制度、
// 章程修改程序、解散後財產歸屬。送件前仍須經所在地民政單位確認。

const TEMPLE_TYPES = {
  祠: { desc: '宗祠、家廟，祭祀祖先', religion: '民間信仰', self: '本祠', orgs: ['clan', 'manager'] },
  堂: { desc: '齋堂、鸞堂、佛堂', religion: '道教', self: '本堂', orgs: ['committee', 'manager', 'ygd'] },
  壇: { desc: '神壇、私人壇', religion: '道教', self: '本壇', orgs: ['manager', 'committee'] },
  宮: { desc: '道教、民間信仰宮廟', religion: '道教', self: '本宮', orgs: ['committee', 'manager', 'assembly'] },
  寺: { desc: '佛教寺院', religion: '佛教', self: '本寺', orgs: ['abbot', 'assembly'] },
  殿: { desc: '道教、民間信仰殿宇', religion: '道教', self: '本殿', orgs: ['committee', 'manager', 'assembly'] },
};

const ORG_TYPES = {
  committee: { name: '管理委員會制', hasCommittee: true, basis: '內政部道教宮廟章程範例（管理委員會制）', head: '主任委員' },
  manager:   { name: '管理人制（無委員會）', hasCommittee: false, basis: '內政部道教宮廟章程範例（管理人制）', head: '管理人' },
  assembly:  { name: '信徒大會制', hasCommittee: true, basis: '內政部佛教寺院章程範例（信徒大會制）', head: '主任委員' },
  abbot:     { name: '執事會制（住持）', hasCommittee: true, basis: '內政部佛教寺院章程範例（執事會制）', head: '住持' },
  ygd:       { name: '一貫道管理委員會制', hasCommittee: true, basis: '內政部一貫道佛堂章程範例（管理委員會制）', head: '主任委員' },
  clan:      { name: '派下員大會制（祭祀公業）', hasCommittee: true, basis: '祭祀公業條例（規約）', head: '管理人' },
};

const CHARTER_DEFAULTS = {
  members: 15, standing: 5, alternates: 3, supervisors: 5, term: 4, age: 20,
  area: '本縣市', years: 1, meetEvery: 3, closeMonths: 3,
  heir: '所在地之地方自治團體',
};

function charterParams(t) {
  const p = Object.assign({}, CHARTER_DEFAULTS, t.charter || {});
  const ty = TEMPLE_TYPES[t.type] || TEMPLE_TYPES['宮'];
  return Object.assign(p, {
    name: t.name || '○○宮', self: ty.self, religion: t.religion || (t.org === 'ygd' ? '一貫道' : ty.religion),
    deity: t.deity || '○○○', address: t.address || '○○縣○○鄉○○路○號',
    member: t.org === 'clan' ? '派下員' : '信徒',
  });
}

// 回傳 [{title, articles:[...]}]
function buildCharter(t) {
  const o = t.org || 'committee';
  const p = charterParams(t);
  const S = p.self, M = p.member;
  const ch = [];

  ch.push({ title: '第一章　總則', articles: [
    `${S}定名為「${p.name}」（以下簡稱${S}）。`,
    o === 'clan'
      ? `${S}為祭祀公業，以祭祀祖先、聯繫宗誼為目的。`
      : `${S}宗教別為${p.religion}，主祀${p.deity}。`,
    `${S}設於${p.address}。`,
    o === 'clan'
      ? `${S}以祭祀祖先、維護祖產、敦睦宗親、獎掖後進為宗旨。`
      : `${S}以弘揚${p.religion}教義、崇奉神明、淨化人心，並辦理公益慈善及社會教化事業為宗旨。`,
    `${S}辦理下列事業：一、祭典、法會及宗教活動。二、信眾祈福、點燈及其他宗教服務。三、公益慈善、獎助學金及社會教化。四、文化資產及建物維護。五、其他符合宗旨之事業。`,
  ]});

  if (o === 'clan') {
    ch.push({ title: '第二章　派下員', articles: [
      `${S}派下員依祭祀公業條例規定，以設立人及其男系子孫（含養子）繼承者為原則；女子、養女、贅婿等依規約或派下員大會決議並依法定程序列為派下員。`,
      `派下員應登錄於派下全員系統表及派下員名冊，異動時應於事實發生後辦理變動報備。`,
      `派下員享有出席派下員大會、選舉、罷免及表決之權利，並負遵守規約及大會決議之義務。`,
    ]});
  } else {
    ch.push({ title: `第二章　${M}`, articles: [
      `凡年滿${p.age}歲，設籍${p.area}滿${p.years}年，贊同${S}宗旨，填具申請書經${o === 'manager' ? '管理人' : o === 'abbot' ? '執事會' : '管理委員會'}審查通過，並登錄於${M}名冊者，為${S}${M}。`,
      `${M}享有${o === 'manager' ? '參與' : '選舉、被選舉、罷免及表決'}${S}事務之權利，並負遵守章程及決議、維護${S}譽之義務。`,
      `${M}有下列情形之一者，喪失其資格：一、死亡。二、自願退出。三、喪失設籍條件。四、違反章程情節重大，經${o === 'manager' ? '管理人' : '信徒大會'}決議除名。`,
    ]});
  }

  const org = [];
  if (o === 'committee' || o === 'ygd' || o === 'assembly') {
    org.push(
      `${S}以信徒大會為最高權力機構；閉會期間由管理委員會執行${S}務。`,
      `信徒大會職權：一、訂定及修改章程。二、選舉及罷免管理委員、監察委員。三、議決年度預算及決算。四、議決不動產之處分或設定負擔。五、議決解散。六、其他重大事項。`,
      `管理委員會置委員${p.members}人、候補委員${p.alternates}人，由信徒大會就${M}中選舉之；委員互選常務委員${p.standing}人，並由常務委員中選舉主任委員、副主任委員各一人。`,
      `管理委員會職權：一、執行信徒大會決議。二、擬訂年度工作計畫、預算及決算。三、管理${S}財產及收支。四、聘任總幹事及工作人員。五、其他依章程應辦事項。`,
      `監察委員會置監察委員${p.supervisors}人，由信徒大會選舉之，互選常務監察委員一人。監察委員會負責監察會務、稽核財務及審核決算。`,
      `主任委員綜理${S}務，對外代表${S}，並為寺廟登記之負責人。`,
      `委員及監察委員任期${p.term}年，連選得連任；主任委員連任以一次為限。委員出缺時由候補委員依序遞補，其任期以補足原任期為限。`,
      `${S}得置總幹事一人，承主任委員之命處理日常事務；並得聘顧問若干人。`,
    );
  } else if (o === 'manager') {
    org.push(
      `${S}置管理人一人，綜理${S}務，對外代表${S}，並為寺廟登記之負責人。`,
      `管理人由創建人擔任，或由${M}推選產生；管理人得以書面指定繼任人，未指定者由${M}過半數推選之。`,
      `管理人任期${p.term}年，連任不受限制；管理人因故不能執行職務時，由其指定之代理人代理。`,
      `管理人得聘請協助人員或顧問若干人，協助辦理祭典、財務及日常事務。`,
      `${S}不設管理委員會；重大事項（不動產處分、章程修改、解散）應召開${M}會議議決之。`,
    );
  } else if (o === 'abbot') {
    org.push(
      `${S}置住持一人，綜理寺務，對外代表${S}，並為寺廟登記之負責人。住持由執事會就具僧籍、戒臘滿五年以上者推選之。`,
      `${S}設執事會，置執事${p.standing}至${p.members}人，由住持聘任，協助處理法務、寺務及財務。`,
      `執事會職權：一、議決年度計畫、預算及決算。二、管理${S}財產。三、議決不動產處分或設定負擔。四、其他重大寺務。`,
      `${S}得置監院或知客等職事，由住持指派；並得設護法會，由${M}組成，協助推動弘法及公益事業。`,
      `住持任期${p.term}年，連選得連任；住持出缺時，由執事會於三個月內推選繼任人。`,
    );
  } else if (o === 'clan') {
    org.push(
      `${S}以派下員大會為最高權力機構。`,
      `${S}置管理人一人，由派下員大會選任，綜理公業事務，對外代表${S}；並得置監察人${p.supervisors > 3 ? 3 : p.supervisors}人，監察財務及業務。`,
      `管理人任期${p.term}年，連選得連任；管理人之選任或解任，應於三十日內報請主管機關備查。`,
      `管理人職權：一、執行派下員大會決議。二、管理公業財產及收支。三、辦理祭祀事宜。四、編造年度收支報告。`,
    );
  }
  ch.push({ title: '第三章　組織及職權', articles: org });

  const meet = [];
  if (o === 'clan') {
    meet.push(
      `派下員大會每年召開一次，由管理人召集；經派下員五分之一以上連署請求時，應召開臨時會。召開時應於十五日前通知。`,
      `派下員大會應有派下員過半數出席，出席人數過半數同意行之。規約變更、財產處分及解散，應有派下員三分之二以上出席，出席人數四分之三以上同意行之。`,
    );
  } else if (o === 'manager') {
    meet.push(
      `${M}會議每年至少召開一次，由管理人召集，應於十日前通知。`,
      `${M}會議應有${M}過半數出席，出席過半數同意行之；章程修改、不動產處分及解散，應有${M}三分之二以上出席，出席三分之二以上同意行之。`,
    );
  } else if (o === 'abbot') {
    meet.push(
      `執事會每${p.meetEvery}個月開會一次，由住持召集並擔任主席；必要時得召開臨時會。`,
      `執事會應有執事過半數出席，出席過半數同意行之；不動產處分及章程修改，應有執事三分之二以上出席，出席三分之二以上同意行之。`,
    );
  } else {
    meet.push(
      `信徒大會每年召開一次，由主任委員召集；經管理委員會認為必要、${M}五分之一以上連署或監察委員會函請時，應召開臨時會。召開時應於十五日前通知。`,
      `信徒大會應有${M}過半數出席，出席人數過半數同意行之。章程變更、不動產處分、委員罷免及解散，應有${M}三分之二以上出席，出席人數三分之二以上同意行之。`,
      `管理委員會每${p.meetEvery}個月開會一次，由主任委員召集；應有委員過半數出席，出席過半數同意行之。監察委員得列席。`,
    );
  }
  ch.push({ title: '第四章　會議', articles: meet });

  const ctl = o === 'manager' ? '管理人' : o === 'abbot' ? '執事會' : o === 'clan' ? '管理人' : '管理委員會';
  const audit = (o === 'committee' || o === 'ygd' || o === 'assembly') ? '監察委員會審核後，提信徒大會通過' : o === 'clan' ? '監察人審核後，提派下員大會通過' : o === 'abbot' ? '執事會通過' : `公告周知並提${M}會議報告`;
  ch.push({ title: '第五章　財務及會計', articles: [
    `${S}經費來源：一、${M}及信眾捐獻、香油錢。二、點燈及宗教服務收入。三、財產孳息。四、其他收入。`,
    `${S}會計年度自每年一月一日起至十二月三十一日止。`,
    `${S}應設置帳簿，詳實記錄收支；香油及點燈收入應當場開立收據，並依${S}「香油及點燈收入管理辦法」每日結帳。`,
    `${ctl}應於會計年度終了後${p.closeMonths}個月內編造決算，經${audit}，並依規定報主管機關備查。`,
    `${S}不動產及重要財產之處分或設定負擔，應經${o === 'clan' ? '派下員大會' : o === 'manager' ? M + '會議' : o === 'abbot' ? '執事會' : '信徒大會'}決議，並依法報主管機關。`,
    `${S}財產及收入應用於章程所定宗旨及事業，不得分配予任何個人。`,
  ]});

  ch.push({ title: '第六章　附則', articles: [
    `本${o === 'clan' ? '規約' : '章程'}之修改，應依第四章規定之決議方式為之，並報主管機關備查。`,
    `${S}解散時，應經${o === 'clan' ? '派下員大會' : o === 'manager' ? M + '會議' : o === 'abbot' ? '執事會' : '信徒大會'}決議並報主管機關；清算後賸餘財產歸屬${p.heir}。`,
    `本${o === 'clan' ? '規約' : '章程'}未規定事項，依有關法令辦理。`,
    `本${o === 'clan' ? '規約' : '章程'}經${o === 'clan' ? '派下員大會' : o === 'manager' ? M + '會議' : o === 'abbot' ? '執事會' : '信徒大會'}通過，報主管機關備查後施行，修改時亦同。`,
  ]});
  return ch;
}

// 管理辦法：把系統流程寫進廟方內規
function buildRules(t, tier) {
  const p = charterParams(t);
  const S = p.self;
  const head = (ORG_TYPES[t.org] || ORG_TYPES.committee).head;
  const cloud = tier !== 'basic';
  return [{ title: `${p.name}香油及點燈收入管理辦法`, articles: [
    `本辦法依${S}${t.org === 'clan' ? '規約' : '章程'}第五章規定訂定之。`,
    `香油、點燈、捐獻及法會收入，應於收款時以電腦系統登錄並當場列印收據，收據編號由系統依日期自動編列，不得跳號或重號。`,
    `收據作廢時應於系統註記作廢原因並保留原號，不得刪除。`,
    `每日營業結束時，由經手人與另一名人員共同點收現金，核對系統日報表後簽名，並於次一營業日存入${S}專戶。`,
    `每月由系統產出收支月報表，呈${head}核閱${cloud ? '；雲端版本並於每月一日自動寄送' : ''}。`,
    `信眾個人資料僅限${S}務使用，非經本人同意不得提供他人；於字幕機、電視牆或網路公開姓名時，應遮蔽一字，信眾表示不願公開者不得顯示。`,
    cloud ? `系統資料每日自動備份至雲端，並保存七年以上。` : `系統資料每週應備份至外接儲存裝置一次，由${head}指定專人保管，並保存七年以上。`,
    `本辦法經${t.org === 'manager' ? '管理人' : t.org === 'abbot' ? '執事會' : t.org === 'clan' ? '管理人' : '管理委員會'}通過後施行，修正時亦同。`,
  ]}];
}
